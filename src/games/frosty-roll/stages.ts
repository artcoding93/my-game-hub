export type StageTheme = "village" | "factory" | "canyon" | "cave" | "tower";

export interface MovingPlatformSpec {
  /** 발판 왼쪽 끝이 오가는 범위 (타일 열) */
  fromCol: number;
  toCol: number;
  row: number;
  width: number;
  /** px/s */
  speed: number;
}

export interface StageSpec {
  id: number;
  name: string;
  nameKo: string;
  tier: "중급" | "고급";
  theme: StageTheme;
  map: string[];
  /** 적 이동 속도 배율 */
  speedScale: number;
  /** 강화 적: 더 빨리 탈출하고 눈이 빨리 녹는다 */
  enhanced: boolean;
  /** 바람: 눈송이가 옆으로 밀린다 */
  wind: boolean;
  movingPlatforms: MovingPlatformSpec[];
  music: "stage" | "boss";
  /** 스테이지 시작 화면의 한 줄 안내 */
  hint: string;
}

