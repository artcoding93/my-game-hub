/*
 * 스테이지 5개 (고정 화면 32×16 타일). 모두 이 게임을 위해 새로 만든 배치다.
 *
 * 범례: #  벽·바닥 (통과 불가, 방울도 막힘)
 *       =  발판 (아래에서 뛰어 통과, 위에서 착지. 방울은 통과)
 *       .  빈칸
 *       P  플레이어 시작 위치 (그 칸의 바닥에 선다)
 *       c  Cogling · s Springlet · z Zipwind · w Whirlwing(공중) · Q Chime Queen(보스, 공중)
 *
 * 높이 규칙: 위아래 발판 간격은 3~4칸(점프 높이 ≈ 4.6칸). 모든 발판·적 위치에 갈 수 있는지
 * logic/reach.test.ts가 실제 점프 물리로 검사한다(움직이는 발판·방울 밟기 없이).
 * 떠오른 방울은 천장(또는 벽 아래)에 닿으면 가장 가까운 gather 지점으로 모인다. gather 지점은
 * 플레이어가 발판에서 뛰어 닿을 수 있는 곳 위에 둔다(갇힌 적을 터뜨릴 수 있도록).
 */

export type StageTheme = "garden" | "factory" | "tower" | "maze" | "clock";

export interface MovingPlatformSpec {
  /** 발판 왼쪽 끝이 오가는 범위 (타일 열) */
  fromCol: number;
  toCol: number;
  row: number;
  width: number;
  /** px/s */
  speed: number;
}

export interface StageSpec {
  id: number;
  name: string;
  nameKo: string;
  tier: "중급" | "고급";
  theme: StageTheme;
  map: string[];
  /** 적 이동 속도 배율 */
  speedScale: number;
  /** 강화 적: 방울에서 더 빨리 탈출한다 */
  enhanced: boolean;
  /** 바람: 떠오른 방울이 옆으로 밀린다 (6초마다 방향 전환) */
  wind: boolean;
  /** 천장에 닿은 방울이 모이는 x 좌표들 (가장 가까운 곳으로) */
  gather: number[];
  movingPlatforms: MovingPlatformSpec[];
  music: "stage" | "boss";
  /** 스테이지 시작 화면의 한 줄 안내 */
  hint: string;
}

