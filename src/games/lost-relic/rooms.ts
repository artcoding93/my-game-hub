/*
 * Lost Relic 유적 지도 (8개 방, 자체 설계). 각 방은 32×18 타일 고정 화면이다.
 *
 * 범례 (logic/world.ts에서 해석)
 *   #  돌벽(단단함)        .  빈 공간          =  돌 발판(아래에서 통과, 위에 설 수 있음)
 *   H  사다리             ~  무너지는 바닥      ^  주기적으로 솟는 가시      t  횃불(장식)
 *   그 밖의 문자          markers에 정의한 오브젝트(상자·문·적 등). 문자가 놓인 칸이 오브젝트의 맨 아래 칸이다.
 *
 * 방 연결 (모든 연결은 양방향)
 *
 *                 [7 수호자]──은빛 문──[8 유물]
 *                     │석문(퍼즐)          │격자(유물 획득 후)
 *   [1 입구]──[2 창고]──[4 중앙 홀]──균열 벽──[5 석상]
 *                     └──청동 문──[3 함정 회랑]
 *                                    │비밀 석판
 *                                 [6 비밀 보물방]
 *
 * 진행 순서: 2번 상자 B에서 청동 열쇠 → 4번 청동 문 → 3번 비밀 석판 → 6번 숨겨진 상자에서 고대 폭약
 *   → 4번 균열 벽 폭파 → 5번 석상 퍼즐(은빛 열쇠 상자 봉인 해제 + 4번 천장 석문 개방) → 7번 은빛 문
 *   → 8번 유물 → (8번 바닥 격자와 5번 천장 격자가 열림) → 5·4·2번을 거쳐 1번 탈출문
 * 이 순서는 logic/progression.test.ts가 지도 데이터를 직접 탐색해 검증한다.
 */

